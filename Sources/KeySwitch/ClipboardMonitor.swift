import AppKit
import CryptoKit
import KeySwitchCore
import Observation

/// Watches the clipboard and keeps the history of copied text and images on the disk.
@MainActor
@Observable
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    static let maxImageBytes = 20_000_000
    static let defaultDirectory = URL.applicationSupportDirectory
        .appending(path: "KeySwitch/Clipboard", directoryHint: .isDirectory)

    /// Marks of nspasteboard.org and of 1Password for items that must not be kept.
    private static let ignoredTypes = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ].map { NSPasteboard.PasteboardType($0) }

    private(set) var history = ClipboardHistory()

    @ObservationIgnored private let settings = Settings.shared
    @ObservationIgnored private var directory = defaultDirectory
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var thumbnails: [UUID: NSImage] = [:]

    private init() {}

    func start() {
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Reads the history of another folder. The self-test uses a temporary one.
    func useDirectory(_ url: URL) {
        directory = url
        thumbnails = [:]
        load()
    }

    /// Puts the entry in the clipboard and at the top of the history.
    func select(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        switch entry.content {
        case .text(let text):
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
        case .image(let file, _, _, _):
            guard let data = try? Data(contentsOf: directory.appending(path: file)) else { return }
            pasteboard.clearContents()
            pasteboard.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        }
        Selection.lastOwnChange = pasteboard.changeCount
        history.touch(entry.id)
        save()
    }

    func remove(_ entry: ClipboardEntry) {
        if let removed = history.remove(entry.id) { discard([removed]) }
        save()
    }

    func clear() {
        discard(history.clear())
        save()
    }

    /// A small picture of an image entry for a menu or a list.
    func thumbnail(for entry: ClipboardEntry) -> NSImage? {
        guard case .image(let file, let width, let height, _) = entry.content, width > 0, height > 0 else { return nil }
        if let known = thumbnails[entry.id] { return known }
        guard let image = NSImage(contentsOf: directory.appending(path: file)) else { return nil }
        let scale = min(32 / CGFloat(height), 96 / CGFloat(width), 1)
        let size = NSSize(width: max(1, CGFloat(width) * scale), height: max(1, CGFloat(height) * scale))
        let small = NSImage(size: size, flipped: false) { rect in
            image.draw(in: rect)
            return true
        }
        thumbnails[entry.id] = small
        return small
    }

    // MARK: - Watching

    private func poll() {
        let pasteboard = NSPasteboard.general
        if history.limit != settings.clipboardLimit {
            discard(history.setLimit(settings.clipboardLimit))
            save()
        }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        // A selection gesture is at work: its copy and its paste are not the user's.
        guard !Engine.shared.isUsingClipboard else { return }
        lastChangeCount = count
        guard settings.clipboardHistory, count != Selection.lastOwnChange else { return }
        capture(from: pasteboard)
    }

    private func capture(from pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []
        guard !types.contains(.fileURL), !types.contains(where: Self.ignoredTypes.contains) else { return }

        if let text = pasteboard.string(forType: .string), text.contains(where: { !$0.isWhitespace }) {
            guard text.count <= ClipboardHistory.maxTextLength else { return }
            add(.text(text), image: nil)
        } else if let data = Self.pngData(from: pasteboard), data.count <= Self.maxImageBytes,
                  let size = NSBitmapImageRep(data: data).map({ ($0.pixelsWide, $0.pixelsHigh) }) {
            let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            let id = UUID()
            let content = ClipboardEntry.Content.image(
                file: "\(id.uuidString).png", width: size.0, height: size.1, digest: digest)
            add(content, image: data, id: id)
        }
    }

    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func add(_ content: ClipboardEntry.Content, image: Data?, id: UUID = UUID()) {
        if let known = history.entry(matching: content) {
            history.touch(known.id)
        } else {
            if let image, case .image(let file, _, _, _) = content {
                guard write(image, to: directory.appending(path: file)) else { return }
            }
            discard(history.insert(ClipboardEntry(id: id, content: content)))
        }
        save()
    }

    // MARK: - Files

    private var indexFile: URL { directory.appending(path: "history.json") }

    private func load() {
        let entries = (try? Data(contentsOf: indexFile))
            .flatMap { try? JSONDecoder().decode([ClipboardEntry].self, from: $0) } ?? []
        history = ClipboardHistory(entries: entries, limit: settings.clipboardLimit)
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(history.entries) else { return }
        _ = write(data, to: indexFile)
    }

    /// Writes a file that only the user can read.
    private func write(_ data: Data, to url: URL) -> Bool {
        let files = FileManager.default
        do {
            try files.createDirectory(
                at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try data.write(to: url, options: .atomic)
            try files.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return true
        } catch {
            return false
        }
    }

    /// Deletes the image files of entries that left the history.
    private func discard(_ entries: [ClipboardEntry]) {
        for entry in entries {
            thumbnails[entry.id] = nil
            if case .image(let file, _, _, _) = entry.content {
                try? FileManager.default.removeItem(at: directory.appending(path: file))
            }
        }
    }
}
